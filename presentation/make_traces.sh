#!/usr/bin/env bash
# Rebuilds presentation/traces.js from real sr_search runs.
# Usage: presentation/make_traces.sh [BUILD_DIR]   (default: build-rel, Release)
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
build="${1:-$root/build-rel}"
cmake -S "$root" -B "$build" -DCMAKE_BUILD_TYPE=Release >/dev/null
cmake --build "$build" -j 4 --target sr_search sr_generate >/dev/null
data="$root/artifacts/data"
out="$root/artifacts/traces"
mkdir -p "$out"
"$build/sr_generate" "$data" >/dev/null

run() {  # id label problem variant seed iterations population [extra options...]
    local id="$1" label="$2" problem="$3" variant="$4" seed="$5" iterations="$6" population="$7"
    shift 7
    "$build/sr_search" "$data/${problem}_${variant}_train.csv" "$data/${problem}_${variant}_validation.csv" \
        "$data/${problem}_${variant}_test.csv" --seed "$seed" --iterations "$iterations" \
        --population "$population" --label "$label" --trace "$out/$id.json" "$@" >/dev/null
    echo "  $id: $(grep -o '"equation":"[^"]*"' "$out/$id.json" | tail -1)"
}

echo "Runs:"
run spring "Sprężyna F = 2,5x + 0,75 (bez szumu, ziarno 0)" spring clean 0 40 64
run projectile "Rzut pionowy h = v0·t − 4,905t² (bez szumu, ziarno 2)" projectile clean 2 200 100
run constrained "Rzut pionowy z szumem, pow z wykładnikiem całkowitym |e| ≤ 2 (ziarno 3)" projectile noisy 3 150 100 \
    --binary '+,-,*,/,pow' --constraint pow:3:1 --max-exponent 2 --integer-exponent --max-size 15
run oscillator "Oscylator x = 1,5·cos(2t + 0,3) (bez szumu, ziarno 1)" oscillator clean 1 200 100 --unary cos
run failure "Przypadek nieudany: rzut pionowy, ziarno 0 (lokalne optimum)" projectile clean 0 200 100

{
    echo "// Generated by presentation/make_traces.sh from real sr_search runs. Do not edit."
    echo "window.SR_TRACES = ["
    first=1
    for id in spring projectile constrained oscillator failure; do
        [ $first -eq 1 ] || echo ","
        first=0
        cat "$out/$id.json"
    done
    echo "];"
} > "$root/presentation/traces.js"
echo "Wrote presentation/traces.js ($(du -h "$root/presentation/traces.js" | cut -f1))"
